<p>
    L'entre-deux-guerres est une période de transition, moins éclatante que l'âge d'or mais loin
    d'être stérile. On y voit naître un institut de métallurgie, puis, sous le rectorat de Jules
    Yernaux, une section d'électro-mécanique dont le succès sera rapide. C'est également l'époque
    de la construction des laboratoires du boulevard Dolez.
</p>
 
<p>
    En 1935, l'institution adopte enfin le nom qu'elle porte encore : <strong>Faculté Polytechnique
    de Mons</strong>.
