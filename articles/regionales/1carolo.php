Au cœur de la Faculté Polytechnique de Mons, la Régionale Carolo réunit les étudiants originaires de la région de Charleroi.
Elle favorise un fort sentiment d’appartenance et met en valeur la culture du Pays Noir à travers de nombreuses activités.
<br>
Parmi celles-ci : des dégustations de spécialités locales, un souper convivial, des visites de sites emblématiques, et des soirées à thème organisées avec d’autres régionales carolos de Belgique.
Les plus courageux peuvent tenter le célèbre Permis de Boire Carolo, une épreuve redoutable pour les vrais connaisseurs !
<br>
La Régionale Carolo FPMs s’engage aussi à transmettre les valeurs et traditions de la région, à partager son histoire, et à créer des liens solides entre les étudiants.
Elle contribue à renforcer la fierté des origines carolos et à promouvoir la richesse culturelle de Charleroi au sein de la Faculté.
<br>
Composée de cinq étudiants passionnés, elle a su créer un espace unique dédié à la découverte, la convivialité et la célébration du Pays Noir.
