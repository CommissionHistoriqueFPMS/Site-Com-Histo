<p>
    En 1990, Willy Staquet publie <em>Un fleuron intellectuel du Hainaut : la Faculté Polytechnique
    de Mons</em>, qui relate l'histoire de la maison depuis 1837. En 1993, l'ensemble de bâtiments
    du Joncquois est complété par un amphithéâtre de 720 places, le Stievenart.
    <!-- [W] l'appelle l'amphithéâtre Stievenart ; nom officiel à confirmer. -->
</p>
 
<p>
    En 1997, le Roi Albert II assiste à la remise des insignes de Docteur <em>Honoris Causa</em> au
    docteur Didier Dubois, au professeur Horst Kruse et au professeur Zenon Mroz.
    <!-- À VÉRIFIER : [W] attribue la remise au « doyen de l'époque, M. Pilatte », alors que notre
         listing donne Serge Boucher comme Recteur de 1994 à 2006. Doyen de faculté ≠ recteur,
         ou erreur de la source : à trancher avant publication. -->
</p>
 
<p>
    En 2009, la Faculté Polytechnique et l'Université de Mons-Hainaut fusionnent pour former
    l'<strong>Université de Mons</strong>. Après cent septante-deux ans d'indépendance, la FPMs
    devient une faculté de l'UMONS : ses dirigeants cessent de porter le titre de Recteur pour
    reprendre celui de Doyen.
</p>
 
<p>
    En 2012, la Faculté fête ses 175 ans. Elle délivre aujourd'hui les grades d'ingénieur civil dans
    six disciplines : Architecture, Chimie et Science des Matériaux, Électricité, Informatique et
    Gestion, Mécanique et Mines — ainsi que le grade de docteur en sciences appliquées.
</p>
 
<p>
    Voilà notre histoire. N'est-elle pas belle comme un conte ? Un conte écrit avec de la foi (car notre foie est mort), de la
    volonté et de la sueur, et dont les fées s'appelleraient Devillez, Guibal, Macquet, Cornet ou
    Houzeau de Lehaie.
</p>
