<p>
En 1845, le Conseil Provincial approuve un projet de réorganisation qui augmente la durée des études
et crée une section commerciale. L'institution porte alors le nom d'"<b>École de Commerce, d'Industrie et
des Mines du Hainaut</b>". Elle est officiellement reconnue sous ce titre par l'État et bénéficie de subsides
gouvernementaux. Sa population dépasse alors les 40 étudiants, mais retombe à une vingtaine en 1851. Elle décide alors
de se séparer de l'École Industrielle de Charleroi. Cette séparation aura pour conséquence une explosion du nombre
d'étudiants, atteignant 78 en 1856 !
</p><p>
L'accroissement important des progrès scientifiques et industriels et la rapidité de l'essor économique
exige ensuite un développement de l'étendue de la formation des ingénieurs et une plus grande
spécialisation. Outre les diplômes initiaux de mines et de métallurgiste, l'École
organise successivement ceux de chimie en 1853 et de mécanique en 1862, celui des chemins de fer
en 1874 et le diplôme d'ingénieur électricien dès 1887. Les extensions constantes des enseignements
obligent, en 1876, à augmenter la durée des études. L'École marque cette évolution en complétant
son titre par celui de "<b>Faculté Polytechnique du Hainaut</b>" et ses étudiants deviennent enfin des ingénieurs
une fois leur diplôme obtenu.
</p>
<p>
    Les chiffres racontent bien cette adolescence en dents de scie. Après la séparation d'avec
    Charleroi, l'École compte 78 étudiants en 1856, puis 110 en 1859 grâce aux cours spéciaux de
    chimie, de docimasie et de métallurgie créés en 1857. Elle suit ensuite, avec deux ou trois ans
    de retard, les soubresauts de l'industrie charbonnière : 65 étudiants en 1865, l'année où
    Devillez est nommé Directeur, 72 en 1870 à la création du cours de construction des machines et
    des chemins de fer qu'illustrera Léon Halley, 54 en 1871 après le conflit franco-prussien —
    mais plus personne, alors, ne songe à supprimer une École qui a fait ses preuves. En 1874,
    c'est l'euphorie : 127 étudiants.
</p>
<p>
    En 1879, l'institution, trop à l'étroit rue des Ursulines, s'installe rue de Houdain. Guibal,
    retiré depuis 1877, n'eut pas la joie d'y enseigner. Les dernières années de Devillez furent
    pourtant fécondes : le règlement de 1880-1881 subordonne le grade d'ingénieur à quatre années
    d'études complètes, un cours extraordinaire d'électricité est adjoint au cours de physique
    générale en 1882, et le laboratoire spécial d'électricité est inauguré en 1886. Dès 1880, un
    corps professoral rajeuni, partisan des mathématiques supérieures, plaide pour que l'École
    abandonne aux autres institutions de la province la formation des contremaîtres et se consacre
    aux connaissances scientifiques approfondies. Devillez n'était pas d'accord ; il eut le grand
    mérite de ne pas s'y opposer.
</p>
 
<p>
    Le 30 octobre 1887, pour le cinquantenaire, le duc d'Ursel, gouverneur de la province et
    représentant du Roi, remet à Devillez les insignes de Commandeur de l'Ordre de Léopold et confie
    à J. Alardin, président de la Société Générale des Étudiants, notre tout premier drapeau :
    « symbole d'union et d'attachement à votre École et à la Patrie ». Les deux guerres que le pays
    allait connaître ne démentiraient pas la formule.
</p><p>
Guibal meurt le 16 septembre 1888. En 1889, Devillez se retire de son poste de Directeur, après 51 années à diriger l'École.
Il rejoindra son compagnon Guibal le 9 février 1891.</p>