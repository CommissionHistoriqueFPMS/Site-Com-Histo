<p>
    Le bâtiment que nous occupons rue de Houdain n'a pas toujours été le nôtre. À l'origine, c'est
    le collège de Houdain, un collège d'humanités fondé en 1545 par le Magistrat de la Ville de
    Mons, au cœur de l'ancien jardin de l'hôpital de Houdain. L'édifice actuel date du premier tiers
    du XVIII<sup>e</sup> siècle : il a été dessiné puis reconstruit de 1735 à 1739 par l'architecte
    Claude-J. de Bettignies, à qui l'on doit aussi le campanile de Sainte-Élisabeth. L'aile
    originelle est surmontée d'un campanile ajouré et de lucarnes d'agrément.
</p>
 
<p>
    Intégré en 1781 à l'Hôpital du Saint-Esprit et au Bureau de Bienfaisance, le collège prend le
    nom de caserne du Saint-Esprit. Supprimé en 1794, il est ensuite occupé par des ateliers. C'est
    l'École des Mines qui le récupère en 1878 et s'y installe l'année suivante. La partie centrale
    et l'aile de droite actuelles sont l'œuvre de l'architecte Hector Puchot, entre 1900 et 1904.
</p>
 
<p>
    Au centre de la cour d'honneur, le monument de bronze installé en 1902 représente Guibal et
    Devillez, fondateurs de l'École. Il est dû au sculpteur L. Devillez. L'ensemble, vaste et
    austère, compte quatre niveaux dont un rez-de-chaussée orné d'une belle galerie de neuf arcades
    en plein cintre ; à l'intérieur, un remarquable escalier en fonte et en petit granit de
    Soignies. Outre le site historique de la Faculté, ces bâtiments abritent aujourd'hui un espace
    muséal.
</p>