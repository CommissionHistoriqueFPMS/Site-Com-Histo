<p>
    La paix revenue, la Faculté se réorganise, étoffe ses cadres et poursuit son efflorescence. Le
    diplôme d'ingénieur civil électromécanicien est supprimé et remplacé par les deux diplômes
    d'ingénieur civil électricien et d'ingénieur civil mécanicien. De nouveaux grades sont
    successivement créés en Chimie, en Architecture et en Techniques Opérationnelles, ce dernier
    devenant plus tard Informatique et Gestion.
</p>
 
<p>
    Mais cette période restera surtout celle d'un bâtisseur : Pierre Houzeau de Lehaie. On lui doit
    une série impressionnante de constructions: le Centre de recherches nucléaires de la rue
    Brisselot, les laboratoires de la rue de l'Épargne et de la rue du Joncquois, et la cité
    estudiantine qui porte aujourd'hui son nom. Au cours des années soixante, les deux bâtiments
    historiques de la rue de Houdain et du boulevard Dolez sont devenus trop exigus face à
    l'expansion du nombre d'étudiants, des recherches et des laboratoires : la Faculté se lance dans
    la construction d'un Institut de Chimie-Métallurgie et d'un Institut de Mécanique-Architecture.
</p>
 
<p>
    Le 4 octobre 1962, le Roi Baudouin remet lui-même à la Fédération des étudiants son deuxième
    drapeau, 75 ans après celui du duc d'Ursel.
    <!-- [W] situe la cérémonie au Théâtre Royal, sous réserve. -->
</p>
 
<p>
    L'État charge enfin la Faculté d'organiser la Faculté des Sciences du Centre Universitaire de
    l'État à Mons (future Université de Mons-Hainaut) et d'ériger les bâtiments de son campus.
</p>