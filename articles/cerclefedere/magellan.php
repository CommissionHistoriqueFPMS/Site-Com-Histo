<p>
    Le Cercle Magellan est le cercle informatique de la Faculté Polytechnique de Mons. Il est composé d'un groupe
    d'étudiants appelés Admins. Cette fine équipe, passionnée par l'informatique, se regroupe régulièrement pour
    jouer aux jeux vidéo ou pour réaliser des projets et solutions informatiques tels que des sites web ou de
    l'hébergement.
</p>
<p>
    Le Magellan est également chargé des réseaux Internet des cités Houzeau et Franeau, et sert de HelpDesk pour
    ces cités étudiantes.
</p>
<p>
    Le Cercle Magellan organise aussi le GAME, une LAN party de 48 h où plus de 200 joueurs participent chaque
    année à plusieurs tournois de jeux vidéo.
</p>
<p>
    Si tu es intéressé par l'informatique, les jeux vidéo, ou simplement curieux d'apprendre, n'hésite pas à nous
    rejoindre au local 500 ou à contacter un membre du comité !
</p>

<h4>Local 500</h4>

<p>
    Nous disposons d'un local au sein de la cité Houzeau (local 500), où nous mettons à disposition des PC en accès
    libre avec une session privée. Les PC disponibles sont très performants et permettent aussi bien de jouer à tes
    jeux préférés que de travailler sur des projets, le tout dans l'ambiance typique du Magellan.
</p>

<h4>Histoire</h4>

<p>
    À l'arrivée d'Internet dans la cité Houzeau, plusieurs personnes se sont découvert une passion pour cela et se
    sont donné comme objectif d'apporter ce flux de données dans tous les kots. Pour y parvenir, ils ont tendu des
    câbles entre les kots, étage par étage, par l'extérieur et les balcons. Il y avait donc un responsable du fil
    d'arrivée pour tout l'étage.
</p>
<p>
    Il existe d'ailleurs beaucoup d'anecdotes : par exemple, certains bourgeois allaient se plaindre car leur
    responsable débranchait tous les autres de l'étage pour télécharger plus vite ! Le réseau de la cité était né,
    et déjà autogéré par les étudiants.
</p>
<p>
    À l'origine, le local 500 était sous la responsabilité du Cercle Culturel, avec un délégué Magellan. Le Culturel
    ayant une trop grande charge de travail et le réseau demandant de plus en plus d'implication, il a été décidé en
    2002 de rendre le Magellan indépendant.
</p>

