Bienvenue dans la Régionale de la Centrale, un joyau au cœur de la Belgique qui sait se démarquer malgré sa modestie en taille.

Ce qui nous rend si spéciaux, c’est notre folklore exceptionnel, qui accompagne chacune de nos activités au son des tambours et des trompettes.
Notre orchestre de rondeaux, composé d’étudiants et d’anciens, est la fierté de notre région.<br>

Nous rassemblons les jeunes venus de Binche à Soignies, en passant par La Louvière et les communes environnantes.
Mais au-delà de nos origines, nous formons avant tout une grande famille unie par des liens indéfectibles.<br>

Chaque année, des comités débordant d’initiatives s’efforcent d’organiser des activités mémorables, dans le respect de notre riche héritage culturel.<br>

Nos soirées sont légendaires, au point de faire rougir de jalousie les fêtes les plus renommées.
Plusieurs fois par an, nous proposons des dégustations de bières typiques de notre région : l’occasion idéale pour découvrir ou redécouvrir les brasseries et bières emblématiques telles que la Binchoise, la Saint-Feuillien, la Bonne-Espérance, la Barbâr, l’Embuscade ou encore la Bel’Chic.<br>

Le jour de la Saint-Nicolas, patron des étudiants, personne ne résiste à l’apéro chez nous ! Le traditionnel Mouchon réchauffe les cœurs avant de rejoindre le grand cortège estudiantin.<br>

En apothéose de l’année, nous affrétons un car pour le légendaire Carnaval de Binche, où tous nos membres se retrouvent autour d’une bonne bière, célébrant cette tradition ancestrale.<br>

Si tu es originaire de la région, musicien, amateur de folklore ou simplement en quête de bonne ambiance, La Centrale t’accueille à bras ouverts !<br>

