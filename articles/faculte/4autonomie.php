<p>
    La Faculté cesse ses enseignements durant la guerre 1914-1918, sur décision de l'autorité
    occupante, et ne rouvre ses portes qu'après l'armistice.
    <!-- À VÉRIFIER : [P] indique une réouverture en 1919, [B] écrit « fermée de 1914 à 1920 ». -->
</p>
 
<p>
    La reprise est l'occasion d'un examen de conscience. Face à l'évolution rapide des sciences et
    des techniques, la Faculté repense entièrement ses enseignements et les élague de leurs parties
    purement descriptives ou technologiques, de nature encyclopédique. Pour ne pas disperser ses
    moyens, elle a le courage de supprimer plusieurs de ses spécialités et ne conserve que les
    diplômes fondamentaux d'ingénieur civil des mines et d'ingénieur civil métallurgiste, complétés
    par ceux d'ingénieur civil électricien et d'ingénieur géologue. L'ingénieur civil
    électromécanicien sera rétabli plus tard.
</p>
 
<p>
    C'est aussi le moment où l'institution s'émancipe. La Province de Hainaut, sa fondatrice, lui
    consent en 1920 une autonomie complète tout en lui garantissant le maintien de ses subventions.
    La loi du 7 juillet 1920 accorde la personnalité civile à l'« École des Mines et de Métallurgie,
    Faculté Technique de la Province de Hainaut », comme elle le fait le même jour pour les
    universités de Gand et de Liège. Jusque-là institution provinciale, la Faculté s'administre
    désormais souverainement par un Conseil d'Administration qui est en même temps son pouvoir
    organisateur. Ce geste généreux lui vaudra une souplesse de gestion dont elle fera grand usage.
</p>
