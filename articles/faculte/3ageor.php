<p>
    Après l'intérim de M. Lambert, directeur divisionnaire des mines, c'est Auguste Macquet (
    nommé professeur en 1881, homme de la « nouvelle vague » ) qui prend la tête de l'École en 1890.
    Il hérite d'une institution dynamique et avide de grandir, et se donne pour objectif de la
    hisser au niveau des Écoles Spéciales des grandes universités, voire de les devancer sur le
    terrain scientifique. Le résultat dépasse les espérances : de 69 étudiants en 1889, l'École
    passe à 314 en 1900.
</p>
 
<p>
    Macquet s'attelle à la tâche dès son entrée en fonction. En 1891, il rend obligatoires les
    éléments de calcul différentiel et intégral ; en 1894, il renforce encore les mathématiques ;
    en 1898, il réforme l'examen d'admission. L'enjeu est explicite : que les études montoises
    soient en tous points comparables à celles des meilleures écoles spéciales universitaires, afin
    que nul ne puisse contester à nos ingénieurs le bénéfice des lois du 10 avril 1890 et du
    3 juillet 1891 sur la collation des grades académiques. Les cours techniques, eux, sont
    développés autant et parfois davantage qu'à Liège, avec un nombre de travaux pratiques tel que
    l'on peut parler de surmenage. L'École reste ainsi fidèle à sa tradition : accroître le bagage
    scientifique sans jamais lâcher la pratique, sans laquelle il n'est pas de bon ingénieur.
</p>
 
<p>
    Les créations s'enchaînent : cours d'électrochimie et d'électrométallurgie en 1903, exercices de
    laboratoire de mécanique dans la foulée. Le département des sciences minérales est alors dirigé
    par Jules Cornet, savant de réputation internationale : membre de l'Expédition Bia-Francqui en
    1892 en qualité de géologue, il y avait découvert les immenses gisements métallifères du
    Katanga. Sous son impulsion naît sans difficulté le titre d'ingénieur géologue, sur le modèle
    liégeois, accessible en une année complémentaire aux ingénieurs des mines et aux ingénieurs des
    arts miniers et industriels. Le diplôme d'ingénieur électricien, créé en 1887, connaît lui aussi
    un large succès.
</p>
 
<p>
    En 1905, une nouvelle réorganisation spécialise nettement les études selon la nature du diplôme
    convoité, pour une durée variant de trois à cinq ans. Devenir ingénieur des mines,
    métallurgiste, mécanicien ou électricien demande désormais cinq années. La crise de 1900-1903
    est absorbée sans casse (286 étudiants encore en 1905) signe que l'École précède désormais
    l'expansion industrielle au lieu de la subir. Sa renommée franchit les frontières et un grand
    nombre d'étudiants étrangers viennent accomplir leurs études à Mons. Une statistique de 1902 est
    éloquente : sur 298 ingénieurs attachés aux charbonnages du pays, 181 sortent de Mons, contre
    114 de Liège ou de Louvain.
</p>