<p >Lors du 33e festival, une délégation issue de notre belle faculté fit son grand retour après presque 20 ans d’absence et ce malgré des invitations datant d’au moins 1999. C’est en 2006 qu’un certain engouement pour cette manifestation folklorique renaît. Cependant c’est en 2007 que nous avons fait notre grand retour, malgré une tentative avortée l’année précédente. Et notre retour fut plus que festif et chaleureux, accueilli comme des rois par nos homologues bruxellois, nous avons chanté, nous avons affoné, bref nous avons guindaillé tous ensembles.</p>
<p >En parlant de chant, celui présenté par nos six chanteurs de l’époque (Seb Vaesen, Thomas Raes, Gilles Noël, Raph Nardo, Sebastiano Tudisco et Nicolas May) a remporté l’un des plus beaux prix du festival : Le prix de la chanson représentant le mieux les valeurs de l’ULB.</p>
<p >Ce prix résulte bien de la mentalité mise en œuvre notamment par le comité fédé de l’époque dont le but était de renouer une saine amitié entre nous et nos homologues bruxellois et on peut dire que le pari fut plus que réussi. En effet, depuis lors, nous participons tous les ans au festival avec plus ou moins de succès et il n’est pas rare de recroiser quelques gens de la capitale durant nos guindailles.</p>
