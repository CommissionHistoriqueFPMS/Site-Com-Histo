La Radio Extra, c’est le cercle qui divertit les étudiants de la Faculté Polytechnique de Mons.
Vieille de 47 ans, elle ne cesse de se renouveler et de proposer des nouveautés chaque année.

La Radio propose de multiples activités : des émissions aux thèmes variés (auxquelles tu peux assister sur place ou depuis chez toi), des soirées ouvertes à tous, mais aussi un souper, un débat d’élections, etc.<br><br>

Mais ce n’est pas tout ! La Radio crée aussi régulièrement du contenu divertissant : vidéos, playlists musicales, et bien plus, disponibles sur nos réseaux.<br>
N’hésite pas à en profiter dès à présent sur nos pages YouTube, Instagram, TikTok et Spotify !
<br><br>
La Radio est également active lors de la Bleusaille, puisqu’elle y anime les Matinales Radio.<br>
Le lieu qui rassemble les batraciens participant à nos activités se situe au local 400 de la cité Houzeau : un endroit idéal pour passer du bon temps, confortablement assis dans des canapés, souvent avec un doux breuvage à la main !

<h4>Histoire</h4>
Autrefois, la Radio était une vraie station émettant en FM.
La première fréquence était 100.2 MHz, puis elle est passée à 106.9 MHz (référence au numéro de la cité).
Cependant, en 2025, la fréquence a été perdue au profit de YOUFM.

