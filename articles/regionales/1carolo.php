<h4>Oripeau des baptisés</h4>
Le foulard carolo est l’emblème du baptisé carolo.<br>
Il fait référence au passé minier de la région : les mineurs le portaient pour ne pas respirer trop de charbon.<br>
Comme la Polytech était autrefois l’école des mines, les ingénieurs le portaient en hommage — à l’envers.
